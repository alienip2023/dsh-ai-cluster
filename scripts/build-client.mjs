#!/usr/bin/env node
// Build the browser half (lib/client.js) from src/panel/*.js.
//   node scripts/build-client.mjs          write lib/client.js
//   node scripts/build-client.mjs --check  fail if lib/client.js is not what the sources build
// The sources are ES modules so tests can import them; the build strips import/export and joins them in one closure,
// so every top-level name must be unique across files (each file uses its own prefix). Single-line imports only.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const dir = path.join(root, 'src/panel')
const out = path.join(root, 'lib/client.js')
const ORDER = ['core', 'styles', 'data', 'fleet', 'team', 'tasks', 'settings', 'shell']

const TOP = /^(?:export\s+)?(?:async\s+)?(?:function\*?|const|let|var|class)\s+([A-Za-z_$][\w$]*)/

export function buildClient() {
  const seen = new Map()
  const parts = []
  for (const name of ORDER) {
    const file = path.join(dir, name + '.js')
    if (!existsSync(file)) throw new Error(`missing src/panel/${name}.js`)
    const lines = readFileSync(file, 'utf8').split('\n')
    const kept = []
    for (const line of lines) {
      if (/^import\s/.test(line)) {
        if (!/from\s+['"][^'"]+['"]\s*;?\s*$/.test(line)) throw new Error(`${name}.js: imports must be a single line: ${line}`)
        continue
      }
      if (/^export\s+(default|\*|\{)/.test(line)) throw new Error(`${name}.js: only "export function/const" is supported: ${line}`)
      const m = TOP.exec(line)
      if (m) {
        if (seen.has(m[1])) throw new Error(`top-level name "${m[1]}" is declared in both ${seen.get(m[1])}.js and ${name}.js`)
        seen.set(m[1], name)
      }
      kept.push(line.replace(/^export\s+/, ''))
    }
    parts.push(`    /* ── src/panel/${name}.js ── */\n` + kept.join('\n').replace(/^/gm, '    ').replace(/^ {4}$/gm, ''))
  }
  const body = parts.join('\n\n')
  return `/**
 * dsh-ai-cluster 的浏览器半边。GENERATED by scripts/build-client.mjs from src/panel/*.js — 不要手改，改 src/panel 后重新构建。
 * 零依赖纯 JS（无 JSX/TS/import）。侧栏图标（sidebar.panellist）与面板（main）成对注册，key 必须等于 id。
 */
window.__ModuleLoader__.load({
  id: 'dsh-ai-cluster',
  factory(require) {
    const React = require('react')

${body}

    /* ── 装配 ── */
    const core = createCore(React)
    const data = createData(core)
    const fleet = createFleet(core)
    const team = createTeam(core)
    const tasks = createTasks(core)
    const settings = createSettings(core)
    const css = stylesBase.concat(fleet.css, team.css, tasks.css, settings.css).join('')
    const shell = createShell(core, data, { fleet, team, tasks, settings }, css)

    return {
      inject: ['slots'],
      apply(ctx) {
        ctx.slots.inject('sidebar.panellist', () => ctx.slots.register({
          name: 'sidebar.panellist', id: shellPanelKey, order: 30, label: () => 'AI 集群控制',
        }, shell.PanelIcon))
        ctx.slots.inject('main', () => ctx.slots.register({ name: 'main', key: shellPanelKey }, shell.Panel))
      },
    }
  },
})
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const built = buildClient()
  if (process.argv.includes('--check')) {
    const cur = existsSync(out) ? readFileSync(out, 'utf8') : ''
    if (cur !== built) { console.error('lib/client.js is out of date: run node scripts/build-client.mjs'); process.exit(1) }
    console.log('lib/client.js is up to date')
  } else {
    writeFileSync(out, built)
    console.log(`Built lib/client.js (${built.length} bytes)`)
  }
}
