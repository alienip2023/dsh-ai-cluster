#!/usr/bin/env node
// Build the plugin's source graph into the directory already shipped by files: lib.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const sourceRoot = path.join(root, 'src')
const libRoot = path.join(root, 'lib')
const outputRoot = path.join(libRoot, 'plugin')
const shim = path.join(libRoot, 'index.js')
const graph = new Map()
const inside = (dir, file) => file.startsWith(dir + path.sep)

function references(text) {
  // Skip comments and ordinary literals before recognizing static imports,
  // re-exports, literal dynamic imports, and module-relative asset URLs.
  const tokens = /\/\*[\s\S]*?\*\/|\/\/[^\r\n]*|(?:\bimport\s*(?:\(\s*|\s+(?:[\w$*{},\s]+?\s+from\s*)?)|\bexport\s+(?:\*(?:\s+as\s+[\w$]+)?|\{[^}]*\})\s+from\s*|\bnew\s+URL\(\s*)(['"])(\.{1,2}\/[^'"\r\n]+)\1|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|`(?:\\.|[^`\\])*`/g
  const result = []
  for (const match of text.matchAll(tokens)) {
    if (!match[2]) continue
    const specifier = match[2]
    const start = match.index + match[0].lastIndexOf(match[1] + specifier + match[1]) + 1
    const asset = match[0].startsWith('new')
    if (asset && !/^\s*,\s*import\.meta\.url\s*\)/.test(text.slice(start + specifier.length + 1))) continue
    result.push({ specifier, start, asset })
  }
  return result
}

function visit(file) {
  // Back-references to the public entry must resolve to the shim, never a copy.
  if (file === shim || graph.has(file)) return
  if (!inside(sourceRoot, file) && !inside(libRoot, file)) {
    throw new Error(`Plugin module outside src/ or lib/: ${file}`)
  }
  const text = readFileSync(file, 'utf8')
  const refs = references(text).map(ref => ({ ...ref, target: path.resolve(path.dirname(file), ref.specifier) }))
  graph.set(file, { text, refs })
  for (const ref of refs) {
    if (!ref.asset) visit(ref.target)
  }
}

visit(path.join(sourceRoot, 'plugin/index.js'))

// Existing lib modules remain shared unless they transitively import src.
// In particular, hub/expose-registry.js reaches src/compat today. Copy those
// ancestors too so an installation without src/ never follows that edge.
const copied = new Set([...graph.keys()].filter(file => inside(sourceRoot, file)))
let changed = true
while (changed) {
  changed = false
  for (const [file, { refs }] of graph) {
    if (!copied.has(file) && refs.some(ref => !ref.asset && copied.has(ref.target))) {
      copied.add(file)
      changed = true
    }
  }
}

function destination(file) {
  if (!copied.has(file)) return file
  if (inside(libRoot, file)) return path.join(outputRoot, '_lib', path.relative(libRoot, file))
  const rel = path.relative(sourceRoot, file)
  return path.join(outputRoot, rel.startsWith('plugin' + path.sep) ? rel.slice('plugin/'.length) : rel)
}

const outputs = new Set()
for (const file of [...copied].sort()) {
  const output = destination(file)
  if (outputs.has(output)) throw new Error(`Plugin output collision: ${output}`)
  outputs.add(output)
  const { text, refs } = graph.get(file)
  let rewritten = text
  for (const ref of [...refs].reverse()) {
    let specifier = path.relative(path.dirname(output), destination(ref.target)).split(path.sep).join('/')
    if (!specifier.startsWith('.')) specifier = './' + specifier
    rewritten = rewritten.slice(0, ref.start) + specifier + rewritten.slice(ref.start + ref.specifier.length)
  }
  const built = '// Generated by scripts/build-plugin-entry.mjs; do not edit.\n' + rewritten
  mkdirSync(path.dirname(output), { recursive: true })
  if (!existsSync(output) || readFileSync(output, 'utf8') !== built) writeFileSync(output, built)
}

// Remove files no longer reached by the source graph, after writing new files.
function prune(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name)
    if (entry.isDirectory()) prune(file)
    else if (!outputs.has(file)) rmSync(file)
  }
}
prune(outputRoot)
console.log(`Built ${outputs.size} plugin modules in lib/plugin/`)
